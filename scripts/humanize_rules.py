# ── 词表编译 ────────────────────────────────────────────────────────────────

def compile_rule(rule):
    """把规则里的 regexes / words 编译成可执行的正则列表。"""
    import re
    pats = []
    for rx in rule.get("regexes", []):
        pats.append(re.compile(rx))
    for w in rule.get("words", []):
        pats.append(re.compile(esc(w)))
    return pats


def compiled():
    """返回 {rule_id: [compiled patterns]}。"""
    return {r["id"]: compile_rule(r) for r in RULES}
